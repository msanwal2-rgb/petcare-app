/* ── Availability generation ──────────────────────────────────────────
   Deterministic given a fixed start date. "pattern" shapes the calendar
   so the UI can exercise both a wide-open caretaker and a fully-booked one. */
type AvailPattern = "open" | "busy" | "booked" | "weekends";

function addDays(iso: string, n: number): string {
  const d = new Date(`${iso}T00:00:00Z`);
  d.setUTCDate(d.getUTCDate() + n);
  return d.toISOString().slice(0, 10);
}

export function generateAvailability(
  start: string,
  days: number,
  pattern: AvailPattern
): AvailabilityDay[] {
  const full = [
    { start: "08:00", end: "12:00" },
    { start: "13:00", end: "18:00" },
  ];
  const morning = [{ start: "08:00", end: "12:00" }];
  const evening = [{ start: "16:00", end: "20:00" }];

  return Array.from({ length: days }, (_, i) => {
    const date = addDays(start, i);
    const dow = new Date(`${date}T00:00:00Z`).getUTCDay(); // 0 Sun … 6 Sat
    let slots: { start: string; end: string }[] = [];
    switch (pattern) {
      case "open":
        slots = full;
        break;
      case "busy":
        slots = i % 3 === 0 ? [] : morning;
        break;
      case "booked":
        slots = i === days - 1 ? evening : []; // essentially full — one late opening
        break;
      case "weekends":
        slots = dow === 0 || dow === 6 ? full : evening;
        break;
    }
    return { date, slots };
  });
}

